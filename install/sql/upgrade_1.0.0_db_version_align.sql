-- +----------------------------------------------------------------------
-- 目的：程序版本为 V1.0.0，但早期部署的线上库 dask_config 中残留
--       db_version = 600、system_version = 6.2.0 等旧版本号，与程序版本不一致。
--
-- 背景（重要）：
--   自本次改动起，系统采用「单一版本源」——后台升级页显示的数据库版本
--   直接读取 config/version.php 的程序版本号（1.0.0），不再读取配置表字段。
--   因此：
--     * 只要部署了新代码（app/common/library/helper/UpgradeHelper.php），
--       后台升级页就会显示「数据库版本 V1.0.0」，与程序版本一致。
--     * 配置表里的 db_version / system_version 已成为无效字段，
--       保留或删除都不影响程序运行与升级判定。
--
-- 使用方式（二选一，推荐方案 A）：
--   方案 A【推荐，零数据库写入】：仅部署新代码即可。后台升级页自动显示 V1.0.0，
--          无需执行任何 SQL。适用于不想触碰线上数据库的场景。
--   方案 B【可选，清理冗余字段】：删除配置表中失效的 db_version / system_version
--          两条记录，使线上库结构与全新安装（install.sql）保持一致。
--
-- ⚠️ 执行前必做：
--   1. 整库备份：mysqldump -h<host> -u<user> -p<pass> <dbname> > backup_before_version_align.sql
--   2. 先执行下方「预检」SELECT，确认结果与预期一致后再执行变更。
--   3. 本脚本仅由运维人员在线上手动执行，程序不会自动调用。
--   4. 表前缀默认为 dask_；若线上使用了其他前缀，请全局替换。
-- +----------------------------------------------------------------------

-- ======================================================================
-- 预检（只读）：确认当前两条旧版本记录存在且值符合预期
-- 预期结果：各返回 1 行，db_version=600，system_version=6.2.0（或相近旧值）
-- ======================================================================
SELECT id, name, value
FROM `dask_config`
WHERE name IN ('db_version', 'system_version');

-- ======================================================================
-- 方案 B：清理失效的版本字段（可选）
-- 说明：一条事务内完成，带精确 WHERE 条件（按 name 限定），不触碰其他配置。
-- ======================================================================
START TRANSACTION;

-- B-1. 删除失效的版本配置记录（限定 name，避免误删）
DELETE FROM `dask_config`
WHERE name IN ('db_version', 'system_version');

-- B-2. 核对：确认删除条数应为 2（可用 ROW_COUNT() / 上方 SELECT 结果判断）
-- SELECT ROW_COUNT() AS deleted_rows;

COMMIT;

-- ======================================================================
-- 事后核对（只读）：确认两条记录已不存在，且其他配置未受影响
-- 预期结果：返回 0 行
-- ======================================================================
SELECT id, name, value
FROM `dask_config`
WHERE name IN ('db_version', 'system_version');

