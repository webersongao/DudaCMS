-- @summary   存量用户补齐邮箱并引入身份验证门槛
-- @verify     users:no_email=0
-- @note       幂等，可安全重复执行
-- ============================================================================

-- 1. 为没有邮箱的存量用户填充系统占位邮箱（uid 保证唯一且稳定）。
--    这些是历史账号，无法接收验证邮件，因此同时标记为已验证，避免存量用户被锁死。
UPDATE `dask_users`
SET `email` = CONCAT('u', `uid`, '@ebihu.com'),
    `is_valid_email` = 1
WHERE (`email` IS NULL OR `email` = '');

-- 说明：有手机号但未验证的用户保持原状，需自行走验证流程，不自动放行。
